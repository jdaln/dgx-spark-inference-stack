# Regenerate tools/testdata/soak/stack-context-bundle.txt, the soak filler for
# tools/soak-context.mjs. It is the control-plane source, so soak answers can be checked
# against real code. Prompt token counts shift when it changes; compare soak numbers only
# within one bundle.
#
#   bash tools/build-soak-bundle.sh
#   bash tools/build-soak-bundle.sh --check    # non-zero if the bundle is out of date

set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/lib/common.sh"

OUT="$REPO_DIR/tools/testdata/soak/stack-context-bundle.txt"

# The control plane, in request order.
SOURCES=(
    "request-validator/index.js"
    "waker/index.js"
    "shared/models-config.mjs"
    "gateway.conf"
)

CHECK_ONLY=0
[[ "${1:-}" == "--check" ]] && CHECK_ONLY=1

build() {
    local dest="$1"
    {
        printf '// Long-context soak filler for the dgx-spark-inference-stack control plane.\n'
        printf '// Generated by tools/build-soak-bundle.sh -- do not edit by hand.\n'
        printf '// Sources, in request order:\n'
        for src in "${SOURCES[@]}"; do
            printf '//   - %s\n' "$src"
        done
        printf '\n'

        for src in "${SOURCES[@]}"; do
            [[ -f "$REPO_DIR/$src" ]] || { echo "missing source: $src" >&2; exit 1; }
            printf '\n// ===================== %s =====================\n\n' "$src"
            cat "$REPO_DIR/$src"
            printf '\n'
        done
    } > "$dest"
}

if [[ "$CHECK_ONLY" == "1" ]]; then
    tmp_out="$(make_workspace_tmp_dir soak-bundle)/candidate.txt"
    build "$tmp_out"
    if cmp -s "$tmp_out" "$OUT"; then
        echo "OK: soak bundle is current"
        rm -rf "$(dirname "$tmp_out")"
        exit 0
    fi
    echo "STALE: $OUT does not match its sources; run: bash tools/build-soak-bundle.sh" >&2
    rm -rf "$(dirname "$tmp_out")"
    exit 1
fi

build "$OUT"
chmod 644 "$OUT"
printf 'wrote %s (%s bytes, %s lines)\n' "$OUT" "$(wc -c < "$OUT")" "$(wc -l < "$OUT")"
