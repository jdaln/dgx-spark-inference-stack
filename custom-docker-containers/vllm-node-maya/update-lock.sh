# Regenerate requirements.lock from requirements.in: pip resolves the packages for this
# platform in a container and reports each wheel's sha256. Run it on the Spark (aarch64), the
# image's platform, then rebuild the image.
#
#   bash custom-docker-containers/vllm-node-maya/update-lock.sh
set -euo pipefail
DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
# Python 3.12, as in the image (Ubuntu 24.04).
IMAGE="${PYTHON_IMAGE:-python:3.12-slim}"

docker run --rm -v "$DIR":/w:ro "$IMAGE" sh -c '
  pip install -q --root-user-action=ignore --disable-pip-version-check --dry-run --ignore-installed \
    --only-binary :all: --report /tmp/report.json -r /w/requirements.in >/dev/null 2>/tmp/err \
    || { cat /tmp/err >&2; exit 1; }
  python - <<"PY"
import json

rows = []
for item in json.load(open("/tmp/report.json"))["install"]:
    meta, info = item["metadata"], item["download_info"]
    rows.append((meta["name"].lower().replace("_", "-"), meta["version"],
                 info["archive_info"]["hashes"]["sha256"], info["url"].rsplit("/", 1)[-1]))
print("# Generated by update-lock.sh from requirements.in for linux aarch64, Python 3.12.")
print("# One wheel per package, installed with --require-hashes --only-binary :all: --no-deps.")
for name, version, sha, filename in sorted(rows):
    print(f"# {filename}")
    print(f"{name}=={version} \\")
    print(f"    --hash=sha256:{sha}")
PY' > "$DIR/requirements.lock.new"
mv "$DIR/requirements.lock.new" "$DIR/requirements.lock"
echo "wrote $DIR/requirements.lock ($(grep -c "==" "$DIR/requirements.lock") packages)"
